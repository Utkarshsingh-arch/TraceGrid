/**
 * TraceGrid Analytics Utilities
 * Deterministic aggregation, median calculation, interval bucketing, and RFC-4180 CSV serialization.
 */

export interface TimeBucket {
  bucketIndex: number;
  startDate: string; // ISO string
  endDate: string; // ISO string
  label: string;
  reportedCasesCount: number;
  closedCasesCount: number;
  reportedLeadsCount: number;
  completedTasksCount: number;
}

/**
 * Computes deterministic median from an array of numbers.
 * Returns null if array is empty.
 */
export function calculateMedian(numbers: number[]): number | null {
  if (numbers.length === 0) return null;
  const sorted = [...numbers].sort((a, b) => a - b);
  const mid = Math.floor(sorted.length / 2);
  if (sorted.length % 2 === 0) {
    return Math.round(((sorted[mid - 1] + sorted[mid]) / 2) * 10) / 10;
  }
  return Math.round(sorted[mid] * 10) / 10;
}

/**
 * Computes deterministic arithmetic mean from an array of numbers.
 * Returns null if array is empty.
 */
export function calculateMean(numbers: number[]): number | null {
  if (numbers.length === 0) return null;
  const sum = numbers.reduce((acc, val) => acc + val, 0);
  return Math.round((sum / numbers.length) * 10) / 10;
}

/**
 * Generates contiguous, non-overlapping UTC time buckets across a specified date range.
 */
export function generateTimeBuckets(
  startDate: Date,
  endDate: Date,
  bucketType: 'day' | 'week' | 'month'
): Array<{ start: Date; end: Date; label: string }> {
  const buckets: Array<{ start: Date; end: Date; label: string }> = [];
  const current = new Date(startDate.getTime());

  let bucketIdx = 0;
  while (current < endDate) {
    const bucketStart = new Date(current.getTime());
    let bucketEnd: Date;

    if (bucketType === 'day') {
      bucketEnd = new Date(bucketStart.getTime() + 24 * 60 * 60 * 1000);
    } else if (bucketType === 'week') {
      bucketEnd = new Date(bucketStart.getTime() + 7 * 24 * 60 * 60 * 1000);
    } else {
      // Month (approx 30 days contiguous bucket in UTC)
      bucketEnd = new Date(bucketStart.getTime() + 30 * 24 * 60 * 60 * 1000);
    }

    if (bucketEnd > endDate) {
      bucketEnd = new Date(endDate.getTime());
    }

    const label = `${bucketStart.toISOString().slice(0, 10)} to ${bucketEnd.toISOString().slice(0, 10)}`;
    buckets.push({ start: bucketStart, end: bucketEnd, label });

    current.setTime(bucketEnd.getTime());
    bucketIdx++;
    if (bucketIdx > 366) break; // Defensive bound
  }

  return buckets;
}

/**
 * Sanitizes a CSV cell to prevent CSV Formula Injection (CWE-1236).
 * Prepends a single quote if the value starts with '=', '+', '-', '@', '\t', or '\r'
 * (including leading whitespace), escapes double quotes per RFC-4180, and wraps in double quotes.
 */
export function sanitizeCsvCell(val: unknown): string {
  if (val === null || val === undefined) {
    return '""';
  }
  if (typeof val === 'number') {
    return String(val);
  }
  let str = String(val);
  if (/^\s*[\=\+\-\@\t\r]/.test(str)) {
    str = `'${str}`;
  }
  return `"${str.replace(/"/g, '""')}"`;
}

/**
 * Serializes operational report metrics to RFC-4180 standard CSV with Formula Injection defense.
 */
export function serializeReportToCsv(report: any): string {
  const lines: string[] = [];

  // Header / metadata section
  lines.push(sanitizeCsvCell('TraceGrid Operational Analytics Report'));
  lines.push(`${sanitizeCsvCell('Report ID')},${sanitizeCsvCell(report.reportId)}`);
  lines.push(`${sanitizeCsvCell('Generated At')},${sanitizeCsvCell(report.generatedAt)}`);
  lines.push(`${sanitizeCsvCell('Generated By')},${sanitizeCsvCell(`${report.generatedBy.displayName} (${report.generatedBy.role})`)}`);
  lines.push(`${sanitizeCsvCell('Jurisdiction Scope')},${sanitizeCsvCell(report.scope.jurisdictionCode || 'ALL_JURISDICTIONS')}`);
  lines.push(`${sanitizeCsvCell('Reporting Interval')},${sanitizeCsvCell(`${report.reportingInterval.startDate} to ${report.reportingInterval.endDate}`)}`);
  lines.push('');

  // Section 1: Caseload Summary
  lines.push(sanitizeCsvCell('SECTION 1: CASELOAD SUMMARY'));
  lines.push(`${sanitizeCsvCell('Metric')},${sanitizeCsvCell('Count')}`);
  lines.push(`${sanitizeCsvCell('Total Accessible Cases')},${sanitizeCsvCell(report.caseload.totalCases)}`);
  lines.push(`${sanitizeCsvCell('Reported State')},${sanitizeCsvCell(report.caseload.byState.REPORTED)}`);
  lines.push(`${sanitizeCsvCell('Under Review State')},${sanitizeCsvCell(report.caseload.byState.UNDER_REVIEW)}`);
  lines.push(`${sanitizeCsvCell('Open Active State')},${sanitizeCsvCell(report.caseload.byState.OPEN)}`);
  lines.push(`${sanitizeCsvCell('Closed State')},${sanitizeCsvCell(report.caseload.byState.CLOSED)}`);
  lines.push(`${sanitizeCsvCell('Priority Critical')},${sanitizeCsvCell(report.caseload.byPriority.CRITICAL)}`);
  lines.push(`${sanitizeCsvCell('Priority High')},${sanitizeCsvCell(report.caseload.byPriority.HIGH)}`);
  lines.push(`${sanitizeCsvCell('Priority Medium')},${sanitizeCsvCell(report.caseload.byPriority.MEDIUM)}`);
  lines.push(`${sanitizeCsvCell('Priority Low')},${sanitizeCsvCell(report.caseload.byPriority.LOW)}`);
  lines.push(`${sanitizeCsvCell('New Cases In Period')},${sanitizeCsvCell(report.caseload.newCasesInPeriod)}`);
  lines.push(`${sanitizeCsvCell('Cases Closed In Period')},${sanitizeCsvCell(report.caseload.closedCasesInPeriod)}`);
  lines.push('');

  // Section 2: Task Backlog & Overdue Metrics
  lines.push(sanitizeCsvCell('SECTION 2: INVESTIGATION TASKS BACKLOG'));
  lines.push(`${sanitizeCsvCell('Metric')},${sanitizeCsvCell('Count')}`);
  lines.push(`${sanitizeCsvCell('Total Tasks')},${sanitizeCsvCell(report.tasks.totalTasks)}`);
  lines.push(`${sanitizeCsvCell('Open Active Tasks')},${sanitizeCsvCell(report.tasks.openTasksCount)}`);
  lines.push(`${sanitizeCsvCell('Overdue Active Tasks')},${sanitizeCsvCell(report.tasks.overdueTasksCount)}`);
  lines.push(`${sanitizeCsvCell('Unassigned Open Tasks')},${sanitizeCsvCell(report.tasks.unassignedOpenTasksCount)}`);
  lines.push(`${sanitizeCsvCell('Completed Tasks')},${sanitizeCsvCell(report.tasks.byStatus.COMPLETED)}`);
  lines.push(`${sanitizeCsvCell('Cancelled Tasks')},${sanitizeCsvCell(report.tasks.byStatus.CANCELLED)}`);
  lines.push(`${sanitizeCsvCell('Average Completion (Hours)')},${sanitizeCsvCell(report.tasks.averageCompletionHours ?? 'N/A')}`);
  lines.push(`${sanitizeCsvCell('Median Completion (Hours)')},${sanitizeCsvCell(report.tasks.medianCompletionHours ?? 'N/A')}`);
  lines.push('');

  // Section 3: Pattern Review Queue
  lines.push(sanitizeCsvCell('SECTION 3: CROSS-CASE PATTERN REVIEW QUEUE'));
  lines.push(`${sanitizeCsvCell('Metric')},${sanitizeCsvCell('Count')}`);
  lines.push(`${sanitizeCsvCell('Total Distinct Patterns')},${sanitizeCsvCell(report.patterns.totalDistinctPatterns)}`);
  lines.push(`${sanitizeCsvCell('Unverified Candidates')},${sanitizeCsvCell(report.patterns.unverifiedCandidates)}`);
  lines.push(`${sanitizeCsvCell('Relevant For Followup')},${sanitizeCsvCell(report.patterns.relevantForFollowup)}`);
  lines.push(`${sanitizeCsvCell('Under Review')},${sanitizeCsvCell(report.patterns.underReview)}`);
  lines.push(`${sanitizeCsvCell('Not Relevant')},${sanitizeCsvCell(report.patterns.notRelevant)}`);
  lines.push(`${sanitizeCsvCell('High Priority Patterns')},${sanitizeCsvCell(report.patterns.byPriority.HIGH)}`);
  lines.push(`${sanitizeCsvCell('Medium Priority Patterns')},${sanitizeCsvCell(report.patterns.byPriority.MEDIUM)}`);
  lines.push(`${sanitizeCsvCell('Low Priority Patterns')},${sanitizeCsvCell(report.patterns.byPriority.LOW)}`);
  lines.push('');

  // Section 4: Operational Disclaimers
  lines.push(sanitizeCsvCell('SECTION 4: GOVERNANCE & DISCLAIMERS'));
  lines.push(`${sanitizeCsvCell('Notice')},${sanitizeCsvCell(report.disclaimer)}`);

  return lines.join('\r\n');
}
